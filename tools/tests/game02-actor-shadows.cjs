const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const dir=path.resolve(__dirname,'../../02_brave_guy');
const THREE=require(path.join(dir,'vendor/three/three.module.min.js'));
const {createActorShadows}=require(path.join(dir,'js/actor-shadows.js'));
const make=(x,y,z,visible=true)=>{const root=new THREE.Group();root.position.set(x,y,z);root.visible=visible;return {root};};
const hero={visual:make(5,0,3),form:'student'};
const ally={visual:make(2,1.5,4),pos:new THREE.Vector3(2,0,4)};
const enemy={visual:make(8,0,5),shown:true,def:{radius:.6}};
const hidden={visual:make(1,0,0,false),shown:false,def:{radius:.6}};
const boss={visual:make(4,0,5),shown:true,def:{radius:.6,boss:true},kind:'incubus'};
const ambush={visual:make(4,-.42,9)};
const scene=new THREE.Scene(),shadows=createActorShadows(THREE,scene),shadow=scene.children[0];
const pos=new THREE.Vector3(),scl=new THREE.Vector3(),rot=new THREE.Quaternion(),m=new THREE.Matrix4();
const get=i=>(shadow.getMatrixAt(i,m),m.decompose(pos,rot,scl),[pos.toArray(),scl.toArray()]);
shadows.update(hero,ally,[enemy,hidden,boss],ambush,false);
assert.equal(shadow.count,4);assert.equal(shadow.castShadow,false);assert.equal(shadow.receiveShadow,false);
assert.equal(shadow.material.depthTest,true);assert.equal(shadow.material.depthWrite,false);
const [h]=get(0);assert.equal(h[0],5);assert.ok(h[1]>.01&&h[1]<.1);assert.equal(h[2],3);
const [a]=get(1);assert.equal(a[1],h[1]);
assert.ok(get(2)[1][0]>get(3)[1][0],'Incubus shadow must be wider than regular enemy');
const strength=shadow.geometry.getAttribute('contactOpacity');
assert.ok(strength?.isInstancedBufferAttribute,'actor shadows need individual opacity');
assert.ok(strength.getX(1)<strength.getX(0)*.7,'floating support must not have a dark detached dot');
assert.ok(shadow.material.alphaTest>0,'skip fully transparent shadow fringe');
const caster=actor=>actor.visual.root.add(Object.assign(new THREE.Mesh(),{castShadow:true}));
const [fullHero,,fullBoss,fullMob]=[0,1,2,3].map(i=>strength.getX(i));
const fullWidth=get(0)[1][0];
caster(hero);caster(ally);caster(boss);
shadows.update(hero,ally,[enemy,boss],ambush,true);
assert.equal(shadow.count,4,'sun-backed actors still need an anchor on painted stages');
assert.ok(Math.abs(get(3)[0][0]-8)<.001,'ordinary mobs keep their contact shadow in high quality');
assert.ok(strength.getX(0)>.25&&strength.getX(0)<fullHero*.7,'grounded real-time casters need a visible, restrained contact anchor');
assert.ok(get(0)[1][0]<fullWidth*.9,'small contact anchor must not double the full shadow silhouette');
assert.ok(strength.getX(1)<strength.getX(0)*.56,'hovering real-time casters retain a gentle falloff');
assert.ok(strength.getX(2)<fullBoss*.7);
const rough=strength.getX(3);
assert.ok(Math.abs(rough-fullMob)<.001);
shadows.update(hero,ally,[enemy,boss],ambush,false);
assert.equal(shadow.count,4,'all visible actors need a fallback footprint in low quality');
assert.ok(Math.abs(strength.getX(3)-rough)<.001,'ordinary mob darkness is stable when quality changes');
const before=get(3)[1][0],groundAlpha=strength.getX(3);
enemy.visual.root.position.y=1.65;
shadows.update(hero,ally,[enemy,boss],ambush,false);
assert.ok(get(3)[1][0]>before,'soft footprint spreads slightly as character rises');
assert.ok(strength.getX(3)<groundAlpha*.65);
boss.visual=make(4,0,5);boss.visual.root.scale.setScalar(1.2);ally.visual.root.visible=false;
ambush.visual.root.position.y=0;enemy.visual.root.position.y=3;
shadows.update(hero,ally,[enemy,boss],ambush,false);
assert.equal(shadow.count,4);assert.equal(get(3)[0][1],h[1]);
assert.ok(get(1)[1][0]>get(3)[1][0]);
shadows.update(hero,null,Array(200).fill(enemy),null,false);assert.equal(shadow.count,201);
assert.equal(shadow.instanceMatrix.updateRanges[0].count,201*16);
assert.equal(strength.updateRanges[0].count,201);
const shader={vertexShader:THREE.ShaderLib.basic.vertexShader,fragmentShader:THREE.ShaderLib.basic.fragmentShader};
shadow.material.onBeforeCompile(shader);
assert.match(shader.vertexShader,/vContactOpacity=contactOpacity/);
const modulate=shader.fragmentShader.indexOf('diffuseColor.a*=vContactOpacity;');
assert.ok(modulate>0&&modulate<shader.fragmentShader.indexOf('#include <alphatest_fragment>'));
shadows.update(hero,ally,Array(600).fill(enemy),ambush,false);
assert.equal(shadow.count,512);
shadows.update(null,null,[],null,true);assert.equal(shadow.count,0);

assert.doesNotMatch(fs.readFileSync(path.join(dir,'js/main.js'),'utf8'),/BLOB_GEO/);
console.log('PASS: contact shadows remain at ground height, follow actors, support quality fallback and boss swap, cap at one instanced batch');
