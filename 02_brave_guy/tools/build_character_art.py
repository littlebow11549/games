"""Build exact vector title atlases and the runtime registry from one replacement contract.
No raster source is modified. Requires fonttools and NotoSansCJK-Bold.ttc.
"""
from pathlib import Path
import json,hashlib
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
ROOT=Path(__file__).resolve().parents[1]
PATH=ROOT/'assets/records/brave_guy_character-art.json'
data=json.loads(PATH.read_text())
fonts={lang:TTFont('/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc',fontNumber=index) for lang,index in [('zh-Hant',3),('en',0),('ja',0)]}

def lettering(text,lang):
 font=fonts[lang];glyphs=font.getGlyphSet();cmap=font.getBestCmap();advance=0;paths=[]
 for char in text:
  assert ord(char) in cmap, f'Missing glyph {char}'
  name=cmap[ord(char)];pen=SVGPathPen(glyphs);glyphs[name].draw(pen)
  paths.append(f'<path transform="translate({advance} 0)" d="{pen.getCommands()}"/>')
  advance+=font['hmtx'][name][0]
 scale=min(0.105,790/advance);x=(1200-advance*scale)/2
 return f'<g transform="translate({x:.3f} {180+380*scale:.3f}) scale({scale:.6f} {-scale:.6f})">'+''.join(paths)+'</g>'

# Series 01: four trilingual skill rows + shared live-text dialogue row.
BURST="M38 180 Q170 150 190 35 Q340 92 490 45 Q650 80 820 30 L790 95 L960 38 Q935 115 1155 150 Q1015 190 1055 303 L963 251 Q845 228 760 303 Q530 268 225 320 L260 255 Q190 218 38 180Z"
TALK="M135 65 Q115 35 230 35 H960 Q1090 35 1090 95 V245 Q1090 290 970 290 H650 L560 337 L550 290 H230 Q115 290 115 240 V110 Q115 80 135 65Z"
for id,c in data['characters'].items():
 bright,mid,dark=c['palette']
 parts=['<svg xmlns="http://www.w3.org/2000/svg" width="3600" height="1800" viewBox="0 0 3600 1800" preserveAspectRatio="none">',f'<title>{c["name"]} dialogue and skills series 01</title>', '<defs><pattern id="dots" width="19" height="19" patternUnits="userSpaceOnUse"><circle cx="4" cy="4" r="2.6" fill="#999" opacity=".25"/></pattern></defs>']
 def frame(path):
  return f'<path d="{path}" fill="white" stroke="#171414" stroke-width="15" stroke-linejoin="miter"/><path d="M930 88 Q1000 118 1050 153 L990 215 L900 228Z" fill="url(#dots)"/><path d="M255 271 Q460 246 740 277" fill="none" stroke="{mid}" stroke-width="6"/>'
 for row,labels in enumerate(c['titles']['labels']):
  for col,(lang,text) in enumerate(zip(data['title_grid']['columnsByLanguage'],labels)):
   ident=f'letters-{row}-{col}';glyph=lettering(text,lang)
   parts += [f'<svg x="{col*1200}" y="{row*360}" width="1200" height="360" viewBox="0 0 1200 360"><title>{text}</title><defs><g id="{ident}">{glyph}</g></defs>',frame(BURST),f'<g transform="translate(4 7)"><use href="#{ident}" fill="#171414" stroke="#171414" stroke-width="30"/></g>',f'<use href="#{ident}" fill="{dark}" stroke="{bright}" stroke-width="14" paint-order="stroke fill"/>','</svg>']
 for col,kind in enumerate(['talk','shout','support']):
  parts += [f'<svg x="{col*1200}" y="1440" width="1200" height="360" viewBox="0 0 1200 360"><title>{kind}</title>',frame(BURST if kind=='shout' else TALK),'</svg>']
 parts.append('</svg>');dest=ROOT/c['titles']['source'];dest.write_text(''.join(parts));c['titles']['sha256']=hashlib.sha256(dest.read_bytes()).hexdigest()
PATH.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
(ROOT/'js/character-art-data.js').write_text('// Generated by tools/build_character_art.py; edit assets/records/brave_guy_character-art.json.\nexport const CHARACTER_ART='+json.dumps(data,ensure_ascii=False,indent=1)+';\n')
print('Built 3 vector atlases (36 multilingual titles + 9 dialogue frames), validated all glyphs, generated registry.')
